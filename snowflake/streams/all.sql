-- =====================================================================
-- Streams — capture changes on source tables
-- =====================================================================

SELECT 'Creating Streams' AS status;

CREATE OR REPLACE STREAM ESQ_USER_STREAM ON TABLE ESQ_USER APPEND_ONLY = FALSE;
CREATE OR REPLACE STREAM ESQ_ADDRESS_STREAM ON TABLE ESQ_ADDRESS APPEND_ONLY = FALSE;
