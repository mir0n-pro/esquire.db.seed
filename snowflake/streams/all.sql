SELECT 'Creating Tasks' AS status;

-- ESQ_USER -> ESQ_USER_LOG
CREATE OR REPLACE TASK ESQ_USER_LOG_TASK
  WAREHOUSE = ESQ_WH
  SCHEDULE = '1 MINUTE'
  WHEN SYSTEM$STREAM_HAS_DATA('ESQ_USER_STREAM')
AS
  INSERT INTO ESQ_USER_LOG (USRL_ACTION, USRL_PK, USRL_ET_PK, USRL_NAME, USRL_PATH,
    USRL_REG_OPTION, USRL_ORG_PK, USRL_DELETED_FLG, USRL_DESC,
    USRL_CRL_ID, USRL_REQ_ID, USRL_UID)
  SELECT
    CASE WHEN METADATA$ACTION = 'INSERT' AND METADATA$ISUPDATE = FALSE THEN 'I'
         WHEN METADATA$ACTION = 'INSERT' AND METADATA$ISUPDATE = TRUE  THEN 'U'
         WHEN METADATA$ACTION = 'DELETE' AND METADATA$ISUPDATE = FALSE THEN 'D'
         ELSE 'U' END,
    USR_PK, USR_ET_PK, USR_NAME, USR_PATH,
    USR_REG_OPTION, USR_ORG_PK, USR_DELETED_FLG, USR_DESC,
    USR_CRL_ID, USR_REQ_ID, USR_UID
  FROM ESQ_USER_STREAM
  WHERE METADATA$ACTION = 'INSERT';

